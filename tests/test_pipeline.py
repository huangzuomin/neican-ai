    out = capsys.readouterr().out
    parsed = json.loads(out)
    assert parsed["date"] == "2026-07-01"
    assert parsed["daily_brief"]["exported"] is True
    assert parsed["event_store"]["canonical_events"] == 1
    assert parsed["entity_registry"]["synced"] == 1
    assert parsed["topic_registry"]["synced"] == 1
